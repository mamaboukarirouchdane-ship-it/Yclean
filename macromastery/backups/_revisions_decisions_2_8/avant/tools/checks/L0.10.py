import math, statistics as st
def run(c):
    c('E trans', .4*300-.6*100, 60, 1e-9); c('équilibre', 100/400*100, 25, 1e-9)
    c('A var', .5*12**2+.5*12**2, 144, 1e-9); c('B var', .5*9+.5*9, 9, 1e-9)
    r=[.4,-.6,.2,-.2,.5,-.3,0,.3,-.5,.2]
    c('moy', st.mean(r), 0, 1e-12); c('somme carrés', sum(x*x for x in r), 1.32, 1e-9); c('var', st.variance(r), 0.14667, 1e-5); c('sd', st.stdev(r), 0.383, 0.0005)
    c('ann', st.stdev(r)*math.sqrt(252), 6.08, 0.005); c('mois', st.stdev(r)*math.sqrt(21), 1.75, 0.005)
    e=[100,104,101,107,103,99,105,110]; pk=0; m=0
    for x in e: pk=max(pk,x); m=min(m,x/pk-1)
    c('mdd', m*100, -7.48, 0.005); c('rec', (1/(1+m)-1)*100, 8.08, 0.005); c('dd1', (101/104-1)*100, -2.88, 0.005)
    c('rec50', 1/.5-1, 1.0, 1e-9)
    c('10x1%', (.99**10-1)*100, -9.56, 0.005); c('5x10%', (.9**5-1)*100, -40.95, 0.005)
    mu=-50+0+40; c('E3', mu, -10, 1e-9); v=.5*90**2+.3*10**2+.2*210**2; c('V3', v, 12900, 1e-9); c('sd3', math.sqrt(v), 113.6, 0.05)
    c('1σ', math.erf(1/math.sqrt(2))*100, 68.27, 0.005); c('2σ', math.erf(2/math.sqrt(2))*100, 95.45, 0.005); c('3σ', math.erf(3/math.sqrt(2))*100, 99.73, 0.005)
    p5=math.erfc(5/math.sqrt(2)); c('5σ', p5*1e7, 5.7, 0.05); c('ans', 1/p5/252, 6900, 50)
    c('Ex1a', .45*150-.55*100, 12.5, 1e-9); c('Ex1b', 100/250*100, 40, 1e-9)
    c('Ex2 C sd', math.sqrt(.5*64+.5*64), 8, 1e-9); c('Ex2 D sd', math.sqrt(.5*4+.5*4), 2, 1e-9)
    c('Ex4 dd', (198/220-1)*100, -10, 1e-9); c('Ex4 dd1', (195/210-1)*100, -7.14, 0.005); c('Ex4 rec', (1/.9-1)*100, 11.11, 0.005)
    c('Ex5 E', -30+6+15, -9, 1e-9); c('Ex5 V', .6*41**2+.3*29**2+.1*159**2, 3789.0, 1e-6); c('Ex5 sd', math.sqrt(3789), 61.6, 0.05)
